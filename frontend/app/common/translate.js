function normalizeBainLanguage(language) {
    const value = String(language || '').toLowerCase();

    if (value.startsWith('en') || value.includes('english')) {
        return 'en';
    }

    return 'ro';
}

function getBainLanguage() {
    return normalizeBainLanguage(window.BAIN_PREFERENCES?.language || document.documentElement.lang || 'ro');
}

function bainTranslate(key) {
    const language = getBainLanguage();
    const dictionary = BAIN_TRANSLATIONS[language] || BAIN_TRANSLATIONS.ro;

    return dictionary[key] || BAIN_TRANSLATIONS.ro[key] || key;
}

function translateExactText(text, language) {
    const trimmed = text.trim();

    if (!trimmed) {
        return text;
    }

    for (const pair of BAIN_TEXT_PAIRS) {
        const ro = pair[0];
        const en = pair[1];

        if (language === 'en' && trimmed === ro) {
            return text.replace(trimmed, en);
        }

        if (language === 'ro' && trimmed === en) {
            return text.replace(trimmed, ro);
        }
    }

    return text;
}

function translateRegexText(text, language) {
    let translated = text;

    BAIN_REGEX_PAIRS.forEach((pair) => {
        const roRegex = pair[0];
        const enText = pair[1];

        if (language === 'en') {
            translated = translated.replace(roRegex, enText);
        }
    });

    return translated;
}

function translateTextValue(text) {
    const language = getBainLanguage();
    let translated = translateExactText(text, language);

    if (translated === text && language === 'en') {
        translated = translateRegexText(text, language);
    }

    return translated;
}

function translateTextNodes() {
    if (!document.body) {
        return;
    }

    const ignoredTags = ['SCRIPT', 'STYLE', 'NOSCRIPT', 'TEXTAREA'];
    const walker = document.createTreeWalker(
        document.body,
        NodeFilter.SHOW_TEXT,
        {
            acceptNode(node) {
                const parent = node.parentElement;

                if (!parent) {
                    return NodeFilter.FILTER_REJECT;
                }

                if (ignoredTags.includes(parent.tagName)) {
                    return NodeFilter.FILTER_REJECT;
                }

                if (parent.closest('[data-no-translate]')) {
                    return NodeFilter.FILTER_REJECT;
                }

                if (!node.nodeValue.trim()) {
                    return NodeFilter.FILTER_REJECT;
                }

                return NodeFilter.FILTER_ACCEPT;
            }
        }
    );

    const nodes = [];

    while (walker.nextNode()) {
        nodes.push(walker.currentNode);
    }

    nodes.forEach((node) => {
        const translated = translateTextValue(node.nodeValue);

        if (translated !== node.nodeValue) {
            node.nodeValue = translated;
        }
    });
}

function translatePage() {
    document.querySelectorAll('[data-translate]').forEach((element) => {
        const key = element.dataset.translate;
        element.textContent = bainTranslate(key);
    });

    document.querySelectorAll('[data-translate-placeholder]').forEach((element) => {
        const key = element.dataset.translatePlaceholder;
        element.placeholder = bainTranslate(key);
    });

    document.querySelectorAll('[data-translate-title]').forEach((element) => {
        const key = element.dataset.translateTitle;
        element.title = bainTranslate(key);
    });

    document.querySelectorAll('[data-translate-value]').forEach((element) => {
        const key = element.dataset.translateValue;
        element.value = bainTranslate(key);
    });

    translateTextNodes();
}

let bainTranslateTimer = null;
let bainIsTranslating = false;

function scheduleTranslatePage() {
    if (bainIsTranslating) {
        return;
    }

    clearTimeout(bainTranslateTimer);

    bainTranslateTimer = setTimeout(() => {
        bainIsTranslating = true;
        translatePage();
        bainIsTranslating = false;
    }, 50);
}

window.t = bainTranslate;
window.translatePage = translatePage;

window.addEventListener('bainPreferencesLoaded', translatePage);
document.addEventListener('DOMContentLoaded', () => {
    translatePage();

    const observer = new MutationObserver(() => {
        scheduleTranslatePage();
    });

    observer.observe(document.body, {
        childList: true,
        subtree: true,
        characterData: true
    });
});